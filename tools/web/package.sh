#!/bin/sh
# Create a self-contained static browser package in dist/ (or a directory below dist/).
# The WASM is generated locally and intentionally is not committed to the source repository.
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
out=${1:-dist}
case "$out" in
  /*) ;;
  *) out="$root/$out" ;;
esac

case "$out" in
  "$root/dist"|"$root/dist/"*)
    ;;
  *)
    echo "package.sh: output must be dist/ or a directory inside dist/" >&2
    exit 2
    ;;
esac

stage="${out}.tmp.$$"
trap 'rm -rf "$stage"' EXIT HUP INT TERM
rm -rf "$stage"
mkdir -p "$stage"

JOBS="${JOBS:-2}" "$root/tools/web/build.sh"

for file in sa_game.js sa_game_bg.wasm; do
  if [ ! -s "$root/web/pkg/$file" ]; then
    echo "package.sh: missing web/pkg/$file after the build" >&2
    exit 1
  fi
done

cp -R "$root/web/." "$stage/"
rm -f "$stage/README.md"
: > "$stage/.nojekyll"

cat > "$stage/_headers" <<'HEADERS'
/*
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Embedder-Policy: require-corp
  Cross-Origin-Resource-Policy: same-origin
  X-Content-Type-Options: nosniff

/index.html
  Cache-Control: no-cache

/main.js
  Cache-Control: no-cache

/worker.js
  Cache-Control: no-cache

/loader.js
  Cache-Control: no-cache

/pkg/*.wasm
  Content-Type: application/wasm
  Cache-Control: no-cache
HEADERS

cat > "$stage/BUILD-INFO.txt" <<'INFO'
sa-engine browser package
Generated by tools/web/package.sh.

Serve this directory over HTTP(S); do not open index.html directly as file://.
Choose your own GTA San Andreas folder in the browser. Game files are read locally
and are not part of this package.

This package contains the built-in image data from crates/sa-image. Keep it private.
INFO

mkdir -p "$(dirname -- "$out")"
rm -rf "$out"
mv "$stage" "$out"
trap - EXIT HUP INT TERM

echo "Browser package ready: $out"
echo "Preview with: tools/web/serve.sh --web dist"
